export type BotRow = {
  index: number;
  address: string;
  characterId: number;
  stars: number;
  timeMs: number;
  state: string;
  fundingHash?: string;
  hash?: string;
  reason?: string;
  elapsedMs?: number;
  sentAt?: number;
  blockNumber?: number;
};
export type BotBatch = {
  batchId: string;
  count: number;
  mode?: string;
  version?: string;
  phase: string;
  rows: BotRow[];
  sent: number;
  successful: number;
  failed: number;
  unknown: number;
  averageMs: number | null;
  timingSamples?: number;
  totalMs: number;
  p95Ms?: number | null;
  maxSameBlock?: number;
  peakTxPerSecond?: number;
  totalGasWei?: string;
  rpcFailureCount?: number;
  chainFailureCount?: number;
  transactionResubmissions?: number;
  rpcReadRetries?: number;
  settlementSpanMs?: number;
  blockCount?: number;
  chainSpanSeconds?: number;
  blocks?: { number: number; timestamp: number; hashes: string[]; count: number }[];
};
export type PreparedBatch = { batchId: string; count: number; fundingHash: string; fundingBlock: number };
export type BatchProgress = {
  batchId: string;
  count: number;
  confirmed: number;
  successful: number;
  failed: number;
  blockCount: number;
  chainSpanSeconds: number;
  blocks: NonNullable<BotBatch["blocks"]>;
  receipts: {
    hash: string;
    blockNumber: number;
    status: "success" | "reverted";
    observedAt: number;
    effectiveGasPrice: string;
    event?: {
      characterId: string;
      player: string;
      stars: string;
      timeMs: string;
      ownerShare: string;
      logIndex: number;
    };
  }[];
};
