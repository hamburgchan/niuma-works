import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const read = name => JSON.parse(readFileSync(new URL(name, root), 'utf8').replace(/^\uFEFF/, ''));
const deployment = read('evidence/deployment.json');
const artifact = read('packages/foundry/out/NiumaWorks.sol/NiumaWorks.json');
const contracts = {10143: {NiumaWorks: {address: deployment.address, abi: artifact.abi, inheritedFunctions: {}, deployedOnBlock: parseInt(deployment.blockNumberHex, 16)}}};
const target = new URL('packages/nextjs/contracts/deployedContracts.ts', root);
writeFileSync(target, `// Generated by scripts/export-contract.mjs from the actual testnet deployment.\nimport { GenericContractsDeclaration } from "~~/utils/scaffold-eth/contract";\nconst deployedContracts = ${JSON.stringify(contracts, null, 2).replace('"10143":', '10143:')} as const;\nexport default deployedContracts satisfies GenericContractsDeclaration;\n`);
console.log(`Exported actual chain 10143 deployment to ${fileURLToPath(target)}`);
